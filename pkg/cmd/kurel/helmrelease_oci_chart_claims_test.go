package kurel

import (
	"strings"
	"testing"

	"github.com/go-kure/launcher/pkg/oam"
)

// TestHelmReleaseOCIChart_ClaimsItsSource: helm-controller generates the
// OCIRepository of a HelmRelease's chart template of kind OCIRepository as
// `<namespace>-<name>` in the HelmRelease's namespace, and takes over and later
// deletes whatever holds that name (go-kure/launcher#1072). An ocirepository
// component of that identity is refused; under a Flux namespace the identity is
// the one there. A chart template of kind HelmChart, a chartRef, and an
// ocirepository of another name build as before.
func TestHelmReleaseOCIChart_ClaimsItsSource(t *testing.T) {
	oci := func(name string) oam.Component { return fluxNSComponent(t, name, "ocirepository", nil) }
	release := func(chart map[string]any) oam.Component {
		return fluxNSComponent(t, "web", "helmrelease", map[string]any{"chart": chart})
	}
	refused := func(ns string) string {
		return `OCIRepository.source.toolkit.fluxcd.io "` + ns + `/` + ns + `-web" is generated by both helm-controller for HelmRelease.helm.toolkit.fluxcd.io "` + ns + `/web" (chart.kind OCIRepository) of component "web" and component "` + ns + `-web"`
	}
	for _, tc := range []struct {
		name   string
		fluxNS string
		comps  []oam.Component
		want   string // a substring of the error; "" means it builds
	}{
		{"the generated name", "", []oam.Component{release(hrOCIChart(nil)), oci("default-web")}, refused("default")},
		{"the generated name in the Flux namespace", fluxNSTarget, []oam.Component{release(hrOCIChart(nil)), oci(fluxNSTarget + "-web")}, refused(fluxNSTarget)},
		{"the application namespace's name under a Flux namespace", fluxNSTarget, []oam.Component{release(hrOCIChart(nil)), oci("default-web")}, ""},
		{"another name", "", []oam.Component{release(hrOCIChart(nil)), oci("web-chart")}, ""},
		{"kind HelmChart", "", []oam.Component{
			fluxNSComponent(t, "web", "helmrelease", nil), oci("default-web"),
		}, ""},
		{"chartRef", "", []oam.Component{
			{Name: "web", Type: "helmrelease", Properties: map[string]any{"chartRef": map[string]any{"kind": "OCIRepository", "name": "default-web"}}},
			oci("default-web"),
		}, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := ociBuild(t, tc.fluxNS, nil, tc.comps...)
			switch {
			case tc.want == "" && err != nil:
				t.Fatalf("build: %v", err)
			case tc.want != "" && (err == nil || !strings.Contains(err.Error(), tc.want)):
				t.Fatalf("build error = %v\nwant one containing %s", err, tc.want)
			}
		})
	}
}
