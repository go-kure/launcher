package kurel

import (
	"strings"
	"testing"

	"github.com/go-kure/launcher/pkg/oam"
)

// TestHelmReleaseHelmChart_ClaimsItsChart: helm-controller generates the
// HelmChart of a HelmRelease's chart template of kind HelmChart as
// `<namespace>-<name>`, named after the HelmRelease, in the namespace the
// template's sourceRef names, else the HelmRelease's, and takes over and later
// deletes whatever holds that name (go-kure/launcher#1074). A helmchart
// component of that identity is refused; under a Flux namespace the identity is
// the one there. A sourceRef in another namespace moves the claim there, and a
// chartRef and a helmchart of another name build as before.
func TestHelmReleaseHelmChart_ClaimsItsChart(t *testing.T) {
	chart := func(name string) oam.Component { return fluxNSComponent(t, name, "helmchart", nil) }
	release := func(sourceNamespace string) oam.Component {
		sourceRef := map[string]any{"kind": "HelmRepository", "name": "example"}
		if sourceNamespace != "" {
			sourceRef["namespace"] = sourceNamespace
		}
		return fluxNSComponent(t, "web", "helmrelease", map[string]any{
			"chart": map[string]any{"spec": map[string]any{"chart": "app", "sourceRef": sourceRef}},
		})
	}
	refused := func(ns string) string {
		return `HelmChart.source.toolkit.fluxcd.io "` + ns + `/` + ns + `-web" is generated by both helm-controller for HelmRelease.helm.toolkit.fluxcd.io "` + ns + `/web" (chart.kind HelmChart) of component "web" and component "` + ns + `-web"`
	}
	for _, tc := range []struct {
		name   string
		fluxNS string
		comps  []oam.Component
		want   string // a substring of the error; "" means it builds
	}{
		{"the generated name", "", []oam.Component{release(""), chart("default-web")}, refused("default")},
		{"sourceRef naming the HelmRelease's namespace", "", []oam.Component{release("default"), chart("default-web")}, refused("default")},
		{"the generated name in the Flux namespace", fluxNSTarget, []oam.Component{release(""), chart(fluxNSTarget + "-web")}, refused(fluxNSTarget)},
		{"the application namespace's name under a Flux namespace", fluxNSTarget, []oam.Component{release(""), chart("default-web")}, ""},
		{"sourceRef in another namespace", "", []oam.Component{release("flux-sources"), chart("default-web")}, ""},
		{"another name", "", []oam.Component{release(""), chart("web-chart")}, ""},
		{"chartRef", "", []oam.Component{
			{Name: "web", Type: "helmrelease", Properties: map[string]any{"chartRef": map[string]any{"kind": "HelmChart", "name": "default-web"}}},
			chart("default-web"),
		}, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := ociBuild(t, tc.fluxNS, nil, tc.comps...)
			switch {
			case tc.want == "" && err != nil:
				t.Fatalf("build: %v", err)
			case tc.want != "" && (err == nil || !strings.Contains(err.Error(), tc.want)):
				t.Fatalf("build error = %v\nwant one containing %s", err, tc.want)
			}
		})
	}
}
