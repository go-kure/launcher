// twoConfigMaps is the objects two producers both generate: ConfigMaps "shop/x"
// and "shop/y".
func twoConfigMaps() []*client.Object {
	return []*client.Object{localConfigMapObject("x", nil), localConfigMapObject("y", nil)}
}

// TestGeneratedObjectCollisionError is go-kure/launcher#1338: both checks return
// a typed error, so a caller reads which objects collide and who produces each
// without parsing the message.
func TestGeneratedObjectCollisionError(t *testing.T) {
	scopes := map[string]CollisionScope{
		"CheckCrossDocumentCollisions": CollisionAcrossDocuments,
		"CheckInDocumentCollisions":    CollisionWithinDocument,
	}
	producers := map[string][]string{
		"CheckCrossDocumentCollisions": {`WebApplication "shop/one"`, `WebApplication "shop/two"`},
		"CheckInDocumentCollisions":    {`component "one"`, `component "two"`},
	}
	for _, check := range collisionChecks {
		t.Run(check.name, func(t *testing.T) {
			// R12: the type, its fields, and the sentinel.
			err := check.run([]*client.Object{localConfigMapObject("x", nil)}, []*client.Object{localConfigMapObject("x", nil)})
			var got *GeneratedObjectCollisionError
			if !errors.As(err, &got) {
				t.Fatalf("errors.As did not find a *GeneratedObjectCollisionError in: %v", err)
			}
			if !errors.Is(err, ErrGeneratedObjectCollision) {
				t.Errorf("errors.Is(err, ErrGeneratedObjectCollision) = false for: %v", err)
			}
			if got.Scope != scopes[check.name] {
				t.Errorf("Scope = %v, want %v", got.Scope, scopes[check.name])
			}
			if len(got.Collisions) != 1 {
				t.Fatalf("Collisions = %v, want one", got.Collisions)
			}
			c := got.Collisions[0]
			if c.Group != "" || c.Kind != "ConfigMap" || c.Namespace != "shop" || c.Name != "x" {
				t.Errorf("collision identity = %q %q %q %q, want core ConfigMap shop/x", c.Group, c.Kind, c.Namespace, c.Name)
			}
			if !slices.Equal(c.Producers, producers[check.name]) {
				t.Errorf("Producers = %q, want %q", c.Producers, producers[check.name])
			}
			if want := check.single("x"); err.Error() != want {
				t.Errorf("message = %q, want %q", err.Error(), want)
			}

			// R13: kurel build wraps what the check returns; the type survives it.
			wrapped := errors.Wrapf(err, "application %q", "web")
			var found *GeneratedObjectCollisionError
			if !errors.As(wrapped, &found) || found != got {
				t.Errorf("errors.As on the wrapped error found %v, want the check's own error", found)
			}
			if !errors.Is(wrapped, ErrGeneratedObjectCollision) {
				t.Errorf("errors.Is(wrapped, ErrGeneratedObjectCollision) = false")
			}

			// No collision, no error: a nil result is the untyped nil.
			if err := check.run([]*client.Object{localConfigMapObject("x", nil)}, []*client.Object{localConfigMapObject("y", nil)}); err != nil {
				t.Errorf("distinct objects: unexpected error: %v", err)
			}
		})
	}
}

// TestGeneratedObjectCollisionError_Several is R14: with several collisions the
// type lists each once, in the order the message prints them, and the message is
// the one the checks have always returned for many.
func TestGeneratedObjectCollisionError_Several(t *testing.T) {
	wants := map[string]string{
		"CheckCrossDocumentCollisions": "generated-object collision: 2 generated objects are each produced by more than one document:\n" +
			"  ConfigMap \"shop/x\" is generated by both WebApplication \"shop/one\" and WebApplication \"shop/two\"\n" +
			"  ConfigMap \"shop/y\" is generated by both WebApplication \"shop/one\" and WebApplication \"shop/two\"",
		"CheckInDocumentCollisions": "generated-object collision: 2 generated objects are each produced by more than one application; rename one producer of each:\n" +
			"  ConfigMap \"shop/x\" is generated by both component \"one\" and component \"two\"\n" +
			"  ConfigMap \"shop/y\" is generated by both component \"one\" and component \"two\"",
	}
	for _, check := range collisionChecks {
		t.Run(check.name, func(t *testing.T) {
			err := check.run(twoConfigMaps(), twoConfigMaps())
			var got *GeneratedObjectCollisionError
			if !errors.As(err, &got) {
				t.Fatalf("errors.As did not find a *GeneratedObjectCollisionError in: %v", err)
			}
			if len(got.Collisions) != 2 || got.Collisions[0].Name != "x" || got.Collisions[1].Name != "y" {
				t.Fatalf("Collisions = %v, want x then y", got.Collisions)
			}
			if err.Error() != wants[check.name] {
				t.Errorf("message = %q\nwant %q", err.Error(), wants[check.name])
			}
		})
	}
}

// TestGeneratedObjectCollisionError_Claim: a collision on the source
// helm-controller generates for a HelmRelease lists the claim among its
// producers, as the message names it.
func TestGeneratedObjectCollisionError_Claim(t *testing.T) {
	const claim = `helm-controller for HelmRelease.helm.toolkit.fluxcd.io "demo/web" (chart.kind OCIRepository)`
	err := CheckInDocumentCollisions([]GeneratedApplication{
		generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", ociChart())),
		generatedApp("other", "other", claimOCIRepository("demo", "demo-web")),
	})
	var got *GeneratedObjectCollisionError
	if !errors.As(err, &got) || len(got.Collisions) != 1 {
		t.Fatalf("err = %v, want one *GeneratedObjectCollisionError with one collision", err)
	}
	c := got.Collisions[0]
	if c.Group != "source.toolkit.fluxcd.io" || c.Kind != "OCIRepository" || c.Namespace != "demo" || c.Name != "demo-web" {
		t.Errorf("collision identity = %q %q %q %q, want OCIRepository.source.toolkit.fluxcd.io demo/demo-web", c.Group, c.Kind, c.Namespace, c.Name)
	}
	if want := []string{claim + ` of component "web"`, `component "other"`}; !slices.Equal(c.Producers, want) {
		t.Errorf("Producers = %q, want %q", c.Producers, want)
	}
	want := `generated-object collision: OCIRepository.source.toolkit.fluxcd.io "demo/demo-web" is generated by both ` + claim + ` of component "web" and component "other"; rename one so that each object has one producer`
	if err.Error() != want {
		t.Errorf("message = %q\nwant %q", err.Error(), want)
	}
}
