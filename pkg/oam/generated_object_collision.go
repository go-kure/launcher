package oam

import (
	"fmt"
	"strings"

	"github.com/go-kure/launcher/pkg/errors"
)

// ErrGeneratedObjectCollision is what the refusal of CheckCrossDocumentCollisions
// and CheckInDocumentCollisions answers to under errors.Is: a generated object that
// more than one document, or more than one application, produces. errors.As with a
// *GeneratedObjectCollisionError finds the same error and says which objects, and
// who produces each.
var ErrGeneratedObjectCollision = errors.New("oam: generated-object collision")

// CollisionScope says which check refused: the producers it compared.
type CollisionScope int

const (
	// CollisionAcrossDocuments is CheckCrossDocumentCollisions: the producers are
	// authored documents.
	CollisionAcrossDocuments CollisionScope = iota + 1
	// CollisionWithinDocument is CheckInDocumentCollisions: the producers are the
	// applications of one document.
	CollisionWithinDocument
)

// ObjectCollision is one generated object that more than one producer makes.
type ObjectCollision struct {
	// Group, Kind, Namespace and Name are the object's identity as the check keys
	// it: the version is no part of it, and the namespace is the one the object
	// carries, empty for a cluster-scoped object.
	Group, Kind, Namespace, Name string
	// Producers names every producer of the object, once each, in the order the
	// check met them: a claim a controller makes for the object comes first and
	// reads "<claim> of <owner>". Two applications that read alike are listed
	// twice here and counted once in the text.
	Producers []string
	// Description is the producers as the text names them: "both A and B", "A, B
	// and C".
	Description string
}

// String returns the collision as the text prints it.
func (c ObjectCollision) String() string {
	id := objectIdentity{group: c.Group, kind: c.Kind, namespace: c.Namespace, name: c.Name}
	return fmt.Sprintf("%s is generated by %s", id, c.Description)
}

// GeneratedObjectCollisionError is the refusal of CheckCrossDocumentCollisions and
// CheckInDocumentCollisions: one or more generated objects that more than one
// producer makes. Its text is the one the checks have always returned, built from
// these fields.
//
// The caller may wrap it (kurel build adds `application "web": …`), so it is found
// with errors.As, or recognised with errors.Is(err, ErrGeneratedObjectCollision).
type GeneratedObjectCollisionError struct {
	// Scope is the check that refused.
	Scope CollisionScope
	// Collisions lists each colliding object once, in the order the check
	// reports them. It is never empty.
	Collisions []ObjectCollision
}

// Error returns the refusal's text.
func (e *GeneratedObjectCollisionError) Error() string {
	lines := make([]string, len(e.Collisions))
	for i, c := range e.Collisions {
		lines[i] = c.String()
	}
	within := e.Scope == CollisionWithinDocument
	if len(lines) == 1 {
		if within {
			return fmt.Sprintf("generated-object collision: %s; rename one so that each object has one producer", lines[0])
		}
		return fmt.Sprintf("generated-object collision: %s", lines[0])
	}
	if within {
		return fmt.Sprintf("generated-object collision: %d generated objects are each produced by more than one application; rename one producer of each:\n  %s",
			len(lines), strings.Join(lines, "\n  "))
	}
	return fmt.Sprintf("generated-object collision: %d generated objects are each produced by more than one document:\n  %s",
		len(lines), strings.Join(lines, "\n  "))
}

// Is makes the error answer to ErrGeneratedObjectCollision under errors.Is.
func (e *GeneratedObjectCollisionError) Is(target error) bool {
	return target == ErrGeneratedObjectCollision
}

// objectCollision builds the collision of id, produced by names: the producers
// listed one by one, described as text names them.
func objectCollision(id objectIdentity, producers []string, description string) ObjectCollision {
	return ObjectCollision{
		Group: id.group, Kind: id.kind, Namespace: id.namespace, Name: id.name,
		Producers: producers, Description: description,
	}
}
