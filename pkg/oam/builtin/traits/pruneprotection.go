package traits

import (
	"github.com/go-kure/kure/pkg/stack"
	"github.com/go-kure/kure/pkg/stack/layout"
	"sigs.k8s.io/controller-runtime/pkg/client"

	"github.com/go-kure/launcher/pkg/oam"
)

// PruneProtectionHandler handles OAM prune-protection traits.
//
// When applied, all Kubernetes resources generated for the component are
// annotated with kustomize.toolkit.fluxcd.io/prune: disabled, preventing
// FluxCD's garbage collector from deleting them. The trait takes no properties.
type PruneProtectionHandler struct{}

// CanHandle returns true for the "prune-protection" trait type.
func (h *PruneProtectionHandler) CanHandle(traitType string) bool {
	return traitType == "prune-protection"
}

// PropertySchema declares the prune-protection trait's properties. It accepts no
// user-facing properties (it is a pure decorator), so the schema is empty.
func (h *PruneProtectionHandler) PropertySchema() map[string]oam.PropertySchema {
	return map[string]oam.PropertySchema{}
}

// Apply wraps app.Config with a pruneProtectedConfig decorator so that every
// resource generated by this application receives the prune-disabled annotation.
//
// "Generated by this application" covers both what the component's
// app.Config returns from Generate and, when that config is a kure
// layout.LayoutAugmenter, every resource on the per-app layout after its
// AugmentLayout ran (e.g. the helmchart component's valuesMode: configMap
// values ConfigMap) — see pruneProtectedConfig.postAugmentLayout.
//
// Narrow scope: only resources produced by the component's own app.Config are
// annotated. Resources appended to bundle.Applications by other trait handlers
// (e.g. rbac, certificate, ingress) are not affected.
func (h *PruneProtectionHandler) Apply(_ *oam.Trait, app *stack.Application, _ *stack.Bundle) error {
	app.Config = wrapIfAugmenter(
		&pruneProtectedConfig{decoratorBase: decoratorBase{Inner: app.Config}},
		app.Config)
	return nil
}

// pruneProtectedConfig wraps an ApplicationConfig and injects
// stack.AnnotationFluxPruneKey = stack.AnnotationFluxPruneDisabled into every
// resource returned by the wrapped config's Generate method, and into every
// resource on the layout its AugmentLayout populates (postAugmentLayout).
type pruneProtectedConfig struct {
	decoratorBase
}

var _ layoutPostAugmenter = (*pruneProtectedConfig)(nil)

func (p *pruneProtectedConfig) Generate(app *stack.Application) ([]*client.Object, error) {
	resources, err := p.Inner.Generate(app)
	if err != nil {
		return nil, err
	}
	for _, r := range resources {
		setPruneDisabled(*r)
	}
	return resources, nil
}

// postAugmentLayout annotates every resource on l and on its child layouts,
// recursively, after the inner LayoutAugmenter ran. kure's layout walker calls
// AugmentLayout only on a per-application layout it seeded with exactly that
// application's own Generate output (pkg/stack/layout/walker.go), so everything
// reachable from l belongs to this component: its Generate output (already
// annotated by Generate above; re-annotating is idempotent) plus whatever the
// augmenter added or moved into children. Sibling applications never share
// this layout, which keeps the trait's narrow scope intact.
func (p *pruneProtectedConfig) postAugmentLayout(l *layout.ManifestLayout) error {
	annotateLayout(l)
	return nil
}

func annotateLayout(l *layout.ManifestLayout) {
	if l == nil {
		return
	}
	for _, r := range l.Resources {
		setPruneDisabled(r)
	}
	for _, c := range l.Children {
		annotateLayout(c)
	}
}

func setPruneDisabled(obj client.Object) {
	if obj == nil {
		return
	}
	ann := obj.GetAnnotations()
	if ann == nil {
		ann = make(map[string]string)
	}
	ann[stack.AnnotationFluxPruneKey] = stack.AnnotationFluxPruneDisabled
	obj.SetAnnotations(ann)
}
