// testLocalConfigKey is the annotation kustomize's build reads to leave an object
// out of its output. It is spelled out here so that these tests state the rule
// without the code under test.
const testLocalConfigKey = "config.kubernetes.io/local-config"

// localConfigAnnotated is an annotation map that carries the local-config key
// with value v.
func localConfigAnnotated(v string) map[string]any {
	return map[string]any{testLocalConfigKey: v}
}

// localConfigMapItem is a ConfigMap in namespace shop, as a list member or a
// generated object, with annotations when any are given.
func localConfigMapItem(name string, annotations map[string]any) map[string]any {
	metadata := map[string]any{"namespace": "shop", "name": name}
	if annotations != nil {
		metadata["annotations"] = annotations
	}
	return map[string]any{"apiVersion": "v1", "kind": "ConfigMap", "metadata": metadata}
}

func localConfigMapObject(name string, annotations map[string]any) *client.Object {
	return collisionObject(&unstructured.Unstructured{Object: localConfigMapItem(name, annotations)})
}

// envelopeAnnotated is an items envelope of apiVersion and kind that carries
// annotations on itself.
func envelopeAnnotated(apiVersion, kind string, annotations map[string]any, items ...any) *client.Object {
	e := envelope(apiVersion, kind, items...)
	if annotations != nil {
		e["metadata"].(map[string]any)["annotations"] = annotations
	}
	return collisionObject(&unstructured.Unstructured{Object: e})
}

// collisionCheck runs one of the two generated-object checks over two producers
// that generate a and b: two documents, or two applications of one document.
type collisionCheck struct {
	name string
	run  func(a, b []*client.Object) error
	// both is the text, less the leading "generated-object collision: ", that names
	// the producers of one object generated by both of them.
	both string
	// tail ends the message of a single collision.
	tail string
}

var collisionChecks = []collisionCheck{
	{
		name: "CheckCrossDocumentCollisions",
		run: func(a, b []*client.Object) error {
			return CheckCrossDocumentCollisions([]GeneratedDocument{generatedDoc("shop", "one", a...), generatedDoc("shop", "two", b...)})
		},
		both: `both WebApplication "shop/one" and WebApplication "shop/two"`,
	},
	{
		name: "CheckInDocumentCollisions",
		run: func(a, b []*client.Object) error {
			return CheckInDocumentCollisions([]GeneratedApplication{generatedApp("one", "one", a...), generatedApp("two", "two", b...)})
		},
		both: `both component "one" and component "two"`,
		tail: "; rename one so that each object has one producer",
	},
}

// single is the whole message of one collision on ConfigMap "shop/<name>".
func (c collisionCheck) single(name string) string {
	return `generated-object collision: ConfigMap "shop/` + name + `" is generated by ` + c.both + c.tail
}

// TestCollisionChecks_SkipWhatKustomizeDrops is go-kure/launcher#1338: an object
// whose config.kubernetes.io/local-config annotation is present and is not the
// string "false" is left out of kustomize's build, so it is never applied and
// generates nothing. Neither check compares it.
func TestCollisionChecks_SkipWhatKustomizeDrops(t *testing.T) {
	cases := []struct {
		name string
		a, b func() []*client.Object
		// want is the whole message of a single collision on ConfigMap "shop/<want>",
		// or "" when the objects are accepted.
		want string
	}{
		{
			// R1
			name: `the first copy carries local-config "true"`,
			a: func() []*client.Object {
				return []*client.Object{localConfigMapObject("x", localConfigAnnotated("true"))}
			},
			b: func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
		},
		{
			// R2: an empty value is not "false", so kustomize drops the object.
			name: `the first copy carries local-config ""`,
			a:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", localConfigAnnotated(""))} },
			b:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
		},
		{
			// R3, not evidence for red: "false" is kept, so this passes before the
			// change as well. It is the control that the filter does not drop every
			// object that carries the key.
			name: `the first copy carries local-config "false"`,
			a: func() []*client.Object {
				return []*client.Object{localConfigMapObject("x", localConfigAnnotated("false"))}
			},
			b:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
			want: "x",
		},
		{
			// R4, a pin: with no annotation the message is the one the check has
			// always returned.
			name: "neither copy carries the annotation",
			a:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
			b:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
			want: "x",
		},
		{
			// R5: the dropped copy is the second producer's.
			name: `the second copy carries local-config "true"`,
			a:    func() []*client.Object { return []*client.Object{localConfigMapObject("x", nil)} },
			b: func() []*client.Object {
				return []*client.Object{localConfigMapObject("x", localConfigAnnotated("true"))}
			},
		},
		{
			name: "both copies are dropped",
			a: func() []*client.Object {
				return []*client.Object{localConfigMapObject("x", localConfigAnnotated("true"))}
			},
			b: func() []*client.Object {
				return []*client.Object{localConfigMapObject("x", localConfigAnnotated("true"))}
			},
		},
		{
			// R6: the List's members are judged one by one, once the List is inlined.
			name: "a List holds a dropped member and a kept one, and both are generated elsewhere",
			a: func() []*client.Object {
				return []*client.Object{envelopeAnnotated("v1", "ConfigMapList", nil,
					localConfigMapItem("dropped", localConfigAnnotated("true")), localConfigMapItem("kept", nil))}
			},
			b: func() []*client.Object {
				return []*client.Object{localConfigMapObject("dropped", nil), localConfigMapObject("kept", nil)}
			},
			want: "kept",
		},
		{
			// R7, not evidence for red: kustomize inlines a List without reading its
			// own annotation, so the members stay and still collide. It passes before
			// the change as well.
			name: `a List that carries local-config "true" holds members that carry none`,
			a: func() []*client.Object {
				return []*client.Object{envelopeAnnotated("v1", "ConfigMapList", localConfigAnnotated("true"),
					localConfigMapItem("kept", nil))}
			},
			b:    func() []*client.Object { return []*client.Object{localConfigMapObject("kept", nil)} },
			want: "kept",
		},
		{
			// R8: an envelope whose kind does not end in List is one node for
			// kustomize, dropped with its items.
			name: `an envelope that is no List carries local-config "true"`,
			a: func() []*client.Object {
				return []*client.Object{envelopeAnnotated("example.com/v1", "Widget", localConfigAnnotated("true"),
					localConfigMapItem("kept", nil))}
			},
			b: func() []*client.Object { return []*client.Object{localConfigMapObject("kept", nil)} },
		},
		{
			// The control for R8: without the annotation the same envelope's member
			// is applied by Flux and collides.
			name: "an envelope that is no List carries no annotation",
			a: func() []*client.Object {
				return []*client.Object{envelopeAnnotated("example.com/v1", "Widget", nil, localConfigMapItem("kept", nil))}
			},
			b:    func() []*client.Object { return []*client.Object{localConfigMapObject("kept", nil)} },
			want: "kept",
		},
	}
	for _, check := range collisionChecks {
		for _, tc := range cases {
			t.Run(check.name+", "+tc.name, func(t *testing.T) {
				err := check.run(tc.a(), tc.b())
				if tc.want == "" {
					if err != nil {
						t.Fatalf("a dropped object was compared: %v", err)
					}
					return
				}
				if want := check.single(tc.want); err == nil || err.Error() != want {
					t.Fatalf("error = %v\nwant %s", err, want)
				}
			})
		}
	}
}

// TestCollisionChecks_SkipTheClaimOfADroppedObject is R9: the claim a HelmRelease
// makes belongs to an object that is applied. A dropped HelmRelease is never
// applied, so helm-controller generates no source for it, and an OCIRepository of
// that name that another producer generates is no collision.
func TestCollisionChecks_SkipTheClaimOfADroppedObject(t *testing.T) {
	helmRelease := func(annotations map[string]string) *client.Object {
		obj := claimHelmRelease(helmGroup, "demo", "web", ociChart())
		if annotations != nil {
			(*obj).SetAnnotations(annotations)
		}
		return obj
	}
	const claimed = `OCIRepository.source.toolkit.fluxcd.io "demo/demo-web"`
	for _, check := range collisionChecks {
		t.Run(check.name+", the HelmRelease is dropped", func(t *testing.T) {
			err := check.run(
				[]*client.Object{helmRelease(map[string]string{testLocalConfigKey: "true"})},
				[]*client.Object{claimOCIRepository("demo", "demo-web")})
			if err != nil {
				t.Fatalf("the claim of a dropped HelmRelease was compared: %v", err)
			}
		})
		// The control: kept, the same HelmRelease claims the name, so this passes
		// before the change as well.
		t.Run(check.name+", the HelmRelease is kept", func(t *testing.T) {
			err := check.run(
				[]*client.Object{helmRelease(nil)},
				[]*client.Object{claimOCIRepository("demo", "demo-web")})
			if err == nil || !strings.Contains(err.Error(), claimed) {
				t.Fatalf("error = %v\nwant one naming %s", err, claimed)
			}
		})
	}
}

// TestSiblingGroup_SkipsAMemberObjectKustomizeDrops is R11: the sibling group
// compares its members' objects by the same rule as the two checks, so an object
// kustomize drops is not one of them (the pkg/oam README says one rule decides
// what the three comparisons key).
func TestSiblingGroup_SkipsAMemberObjectKustomizeDrops(t *testing.T) {
	object := func(p *client.Object) client.Object { return *p }
	cases := []struct {
		name string
		a, b client.Object
		// want is the whole error message; "" means accepted.
		want string
	}{
		{
			name: `one copy carries local-config "true"`,
			a:    object(localConfigMapObject("shared", localConfigAnnotated("true"))),
			b:    object(localConfigMapObject("shared", nil)),
		},
		{
			// The control, which passes before the change as well.
			name: "neither copy carries the annotation",
			a:    object(localConfigMapObject("shared", nil)),
			b:    object(localConfigMapObject("shared", nil)),
			want: `sibling group "web": members "a" and "b" both generate ConfigMap "shop/shared"; exactly one member may`,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			objs, err := siblingGroupOf([]client.Object{tc.a}, []client.Object{tc.b}).Generate(nil)
			if tc.want != "" {
				if err == nil || err.Error() != tc.want {
					t.Fatalf("error = %v\nwant %s", err, tc.want)
				}
				return
			}
			if err != nil {
				t.Fatalf("a dropped object was compared: %v", err)
			}
			// The group still hands out what its members generated, the dropped
			// object included: it is the Kustomization build that drops it.
			var got []client.Object
			for _, p := range objs {
				if p != nil {
					got = append(got, *p)
				}
			}
			if want := []client.Object{tc.a, tc.b}; !slices.Equal(got, want) {
				t.Errorf("group objects = %v, want both objects as generated", got)
			}
		})
	}
}

// TestWarnForcedVolumes_ReadsADroppedObject is R16, a pin: the forced-volume scan
// reads appliedObjects, which keeps an object kustomize drops. The filter belongs
// to the collision checks alone, so this warning does not change.
func TestWarnForcedVolumes_ReadsADroppedObject(t *testing.T) {
	var warnings []string
	tr := NewTransformer(nil, nil)
	tr.SetWarningHandler(func(w string) { warnings = append(warnings, w) })
	dropped := claimObject("shop", "data", map[string]string{fluxForceAnnotation: "enabled", testLocalConfigKey: "true"})
	tr.WarnForcedVolumes([]GeneratedApplication{generatedApp("web", "web", dropped)})
	if !slices.ContainsFunc(warnings, func(w string) bool { return strings.Contains(w, "PersistentVolumeClaim shop/data ") }) {
		t.Fatalf("a force-annotated claim that kustomize drops was not warned about; warnings: %q", warnings)
	}
}
