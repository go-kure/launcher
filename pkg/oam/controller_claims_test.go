// claimHelmRelease is a HelmRelease namespace/name whose spec.chart is chart
// (none when nil), of API group group.
func claimHelmRelease(group, namespace, name string, chart map[string]any) *client.Object {
	u := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": group + "/v2",
		"kind":       "HelmRelease",
		"metadata":   map[string]any{"namespace": namespace, "name": name},
		"spec":       map[string]any{},
	}}
	if chart != nil {
		u.Object["spec"].(map[string]any)["chart"] = chart
	}
	var obj client.Object = u
	return &obj
}

func claimOCIRepository(namespace, name string) *client.Object {
	var obj client.Object = &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "source.toolkit.fluxcd.io/v1",
		"kind":       "OCIRepository",
		"metadata":   map[string]any{"namespace": namespace, "name": name},
	}}
	return &obj
}

func claimHelmChart(namespace, name string) *client.Object {
	var obj client.Object = &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "source.toolkit.fluxcd.io/v1",
		"kind":       "HelmChart",
		"metadata":   map[string]any{"namespace": namespace, "name": name},
	}}
	return &obj
}

func ociChart() map[string]any {
	return map[string]any{"kind": "OCIRepository", "spec": map[string]any{"url": "oci://registry.example.com/charts/app"}}
}

// helmChartTemplate is a chart template of kind HelmChart (unset, its default)
// whose sourceRef names sourceNamespace, or no namespace when it is "".
func helmChartTemplate(sourceNamespace string) map[string]any {
	sourceRef := map[string]any{"kind": "HelmRepository", "name": "charts"}
	if sourceNamespace != "" {
		sourceRef["namespace"] = sourceNamespace
	}
	return map[string]any{"spec": map[string]any{"chart": "app", "sourceRef": sourceRef}}
}

// TestCheckInDocumentCollisions_HelmChartClaims: for a HelmRelease's chart
// template of kind HelmChart, helm-controller generates the HelmChart
// `<namespace>-<name>`, named after the HelmRelease, in the namespace its
// sourceRef names, else the HelmRelease's (go-kure/launcher#1074). It collides
// as the OCIRepository of kind OCIRepository does.
func TestCheckInDocumentCollisions_HelmChartClaims(t *testing.T) {
	const claim = `helm-controller for HelmRelease.helm.toolkit.fluxcd.io "demo/web" (chart.kind HelmChart)`
	cases := []struct {
		name string
		apps []GeneratedApplication
		want string // the whole error message; "" means accepted
	}{
		{
			name: "another component's HelmChart",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate(""))),
				generatedApp("demo-web", "demo-web", claimHelmChart("demo", "demo-web")),
			},
			want: `generated-object collision: HelmChart.source.toolkit.fluxcd.io "demo/demo-web" is generated by both ` + claim + ` of component "web" and component "demo-web"; rename one so that each object has one producer`,
		},
		{
			name: "the HelmRelease's own application",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate("")), claimHelmChart("demo", "demo-web")),
			},
			want: `generated-object collision: HelmChart.source.toolkit.fluxcd.io "demo/demo-web" is generated by both ` + claim + ` of component "web" and component "web"; rename one so that each object has one producer`,
		},
		{
			name: "kind HelmChart named explicitly",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", map[string]any{"kind": "HelmChart", "spec": helmChartTemplate("")["spec"]})),
				generatedApp("demo-web", "demo-web", claimHelmChart("demo", "demo-web")),
			},
			want: `generated-object collision: HelmChart.source.toolkit.fluxcd.io "demo/demo-web" is generated by both ` + claim + ` of component "web" and component "demo-web"; rename one so that each object has one producer`,
		},
		{
			// The namespace follows sourceRef; the name stays the HelmRelease's.
			name: "sourceRef in another namespace",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate("flux-sources"))),
				generatedApp("src", "src", claimHelmChart("flux-sources", "demo-web")),
			},
			want: `generated-object collision: HelmChart.source.toolkit.fluxcd.io "flux-sources/demo-web" is generated by both ` + claim + ` of component "web" and component "src"; rename one so that each object has one producer`,
		},
		{
			name: "sourceRef in another namespace, a HelmChart in the HelmRelease's",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate("flux-sources"))),
				generatedApp("demo-web", "demo-web", claimHelmChart("demo", "demo-web")),
			},
		},
		{
			name: "sourceRef in another namespace, named after that namespace",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate("flux-sources"))),
				generatedApp("src", "src", claimHelmChart("flux-sources", "flux-sources-web")),
			},
		},
		{
			// Under a Flux namespace the HelmRelease is there, and so is its claim.
			name: "the claim follows the HelmRelease's namespace",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "flux-system", "web", helmChartTemplate(""))),
				generatedApp("demo-web", "demo-web", claimHelmChart("flux-system", "demo-web")),
				generatedApp("src", "src", claimHelmChart("flux-system", "flux-system-web")),
			},
			want: `generated-object collision: HelmChart.source.toolkit.fluxcd.io "flux-system/flux-system-web" is generated by both helm-controller for HelmRelease.helm.toolkit.fluxcd.io "flux-system/web" (chart.kind HelmChart) of component "web" and component "src"; rename one so that each object has one producer`,
		},
		{
			name: "two HelmReleases of one name in two namespaces sharing a source namespace",
			apps: []GeneratedApplication{
				generatedApp("a", "a", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate("flux-sources"))),
				generatedApp("b", "b", claimHelmRelease(helmGroup, "other", "web", helmChartTemplate("flux-sources"))),
			},
		},
		{
			name: "a HelmChart of another name",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate(""))),
				generatedApp("web-chart", "web-chart", claimHelmChart("demo", "web")),
			},
		},
		{
			name: "a HelmChart in another namespace",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate(""))),
				generatedApp("demo-web", "demo-web", claimHelmChart("flux-system", "demo-web")),
			},
		},
		{
			name: "an OCIRepository of the claimed name",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmRelease(helmGroup, "demo", "web", helmChartTemplate(""))),
				generatedApp("demo-web", "demo-web", claimOCIRepository("demo", "demo-web")),
			},
		},
		{
			name: "a chartRef",
			apps: []GeneratedApplication{
				generatedApp("web", "web", claimHelmReleaseChartRef("demo", "web")),
				generatedApp("demo-web", "demo-web", claimHelmChart("demo", "demo-web")),
			},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := CheckInDocumentCollisions(tc.apps)
			switch {
			case tc.want == "" && err != nil:
				t.Fatalf("error = %v, want accepted", err)
			case tc.want != "" && (err == nil || err.Error() != tc.want):
				t.Fatalf("error = %v\nwant %s", err, tc.want)
			}
		})
	}
}

// claimHelmReleaseChartRef is a HelmRelease namespace/name with a chartRef and
// no chart template.
func claimHelmReleaseChartRef(namespace, name string) *client.Object {
	obj := claimHelmRelease(helmGroup, namespace, name, nil)
	(*obj).(*unstructured.Unstructured).Object["spec"] = map[string]any{
		"chartRef": map[string]any{"kind": "HelmChart", "name": namespace + "-" + name},
	}
	return obj
}

